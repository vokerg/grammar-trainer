export const languageNames: Record<SupportedLanguage, string> = {
  da: 'Dansk',
  en: 'English',
  de: 'Deutsch',
  ru: 'Русский',
};

type I18nValue = {
  language: SupportedLanguage;
  locale: string;
  setLanguage: (language: SupportedLanguage) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
};

function translate(
  language: SupportedLanguage,
  key: string,
  values: Record<string, string | number> = {},
): string {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

const fallback: I18nValue = {
  language: 'da',
  locale: languageToLocale('da'),
  setLanguage: () => undefined,
  t: (key, values) => translate('da', key, values),
};

const I18nContext = createContext<I18nValue>(fallback);

function initialLanguage(): SupportedLanguage {
  const stored = globalThis.localStorage?.getItem('grammar-trainer:ui-language');
  const parsedStored = SupportedLanguageSchema.safeParse(stored);
  if (parsedStored.success) return parsedStored.data;
  const browser = globalThis.navigator?.language?.slice(0, 2);
  const parsedBrowser = SupportedLanguageSchema.safeParse(browser);
  return parsedBrowser.success ? parsedBrowser.data : 'da';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<SupportedLanguage>(initialLanguage);
  const setLanguage = (next: SupportedLanguage) => {
    setLanguageState(next);
    globalThis.localStorage?.setItem('grammar-trainer:ui-language', next);
  };
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<I18nValue>(
    () => ({
      language,
      locale: languageToLocale(language),
      setLanguage,
      t: (key, values) => translate(language, key, values),
    }),
    [language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
